// Regenerates src/catalog/entries.ts from a local checkout of the Gambit site.
//
//   node tools/sync-catalog.mjs ../hassanireza.github.io
//
// The Gambit stays the source of truth for topic names, chapters, levels and the
// one sentence idea. Ordering for this app lives in src/catalog/curriculum.ts.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repo = resolve(process.argv[2] ?? "../hassanireza.github.io");
const dir = join(repo, "src/pages/Gambit/data");
const files = readdirSync(dir)
  .filter((f) => /^ch\d+-.*\.ts$/.test(f))
  .sort((a, b) => parseInt(a.match(/ch(\d+)/)[1], 10) - parseInt(b.match(/ch(\d+)/)[1], 10));

const clean = (s) => s.replace(/\s*\u2014\s*/g, ", ").replace(/\s*\u2013\s*/g, " to ");
const unesc = (s) => JSON.parse(`"${s}"`);

const entries = [];
for (const f of files) {
  const src = readFileSync(join(dir, f), "utf8");
  const re = /\{\s*i: "([^"]+)",\s*n: "((?:[^"\\]|\\.)*)",(?:\s*fa: "(?:[^"\\]|\\.)*",)?\s*c: "([^"]+)",\s*l: (\d),\s*g: \[[^\]]*\],\s*d: "((?:[^"\\]|\\.)*)"/g;
  let m;
  while ((m = re.exec(src))) {
    entries.push({ slug: m[1], name: clean(unesc(m[2])), chapter: m[3], level: Number(m[4]), idea: clean(unesc(m[5])) });
  }
}

if (entries.length < 100) throw new Error(`Only found ${entries.length} topics. Check the Gambit path: ${dir}`);

const body = entries.map((e) => `  ${JSON.stringify(e)},`).join("\n");
writeFileSync(
  resolve("src/catalog/entries.ts"),
  `// Generated by tools/sync-catalog.mjs from The Gambit. Do not edit by hand.\nimport type { TopicEntry } from "./types";\n\nexport const ENTRIES: TopicEntry[] = [\n${body}\n];\n`,
);
console.log(`Wrote ${entries.length} topics.`);
